"""Inventory of large intermediate files and the storage policy.

The pipeline writes several multi-hundred-MB float32 cubes.  They are derived
data: every one of them is regenerated by the stage that produces it, so none
needs to be archived or uploaded.  This script records the sizes and the rule so
the policy is explicit rather than folklore.

Policy
------
* keep  : everything under `processed/` up to 200 MB — these are cheap to
          regenerate and often needed for inspection;
* keep  : figures, JSON and CSV at any size (small by construction);
* do not archive or upload: `.npy` cubes above 200 MB.  They are reproduced by
          `run_all.py` from `raw/` plus the documented seeds, and the SHA-256 in
          `data_manifest.json` proves the reproduction;
* never delete `raw/`, `processed/*.json`, `processed/*.csv` or the figures.

Outputs: processed/large_files.json
"""
from __future__ import annotations

from pathlib import Path

import common as C

LIMIT_MB = 200


def main():
    rows = []
    for p in sorted(C.PROC.rglob("*")):
        if not p.is_file():
            continue
        size = p.stat().st_size
        if size >= LIMIT_MB * 1024 * 1024:
            rows.append({
                "file": str(p.relative_to(C.PROC)).replace("\\", "/"),
                "mb": round(size / 1024 / 1024, 1),
                "kind": p.suffix.lstrip("."),
                "regenerable": p.suffix == ".npy",
            })
    total = sum(r["mb"] for r in rows)
    C.save_json(C.PROC / "large_files.json", {
        "limit_mb": LIMIT_MB,
        "n_files": len(rows),
        "total_mb": round(total, 1),
        "policy": {
            "keep": "all files below the limit; figures/JSON/CSV at any size",
            "not_uploaded": ".npy cubes above the limit — regenerated by "
                            "run_all.py and verified by data_manifest.json",
            "never_delete": ["raw/", "processed/*.json", "processed/*.csv",
                             "processed/*.png"],
        },
        "files": rows,
    })
    print(f"{len(rows)} files >= {LIMIT_MB} MB, {total:.0f} MB total")
    for r in rows:
        print(f"  {r['mb']:8.1f} MB  {r['file']}")


if __name__ == "__main__":
    main()
